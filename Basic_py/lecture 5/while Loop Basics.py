# 1. Basic while loop: 1 se 5 tak numbers print karna
i = 1
while i <= 5:
    print(i)
    i += 1

print("Loop ended")

# 2. 5 se 1 tak reverse numbers print karna
count = 5
while count >= 1:
    print(count)
    count -= 1

# 3. 1 se 100 tak numbers print karna
num = 1
while num <= 100:
    print(num)
    num += 1
